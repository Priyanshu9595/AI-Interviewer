/**
 * What the bot is about to do, and whether it is actually able to.
 *
 * Auto-join only happens while the server is running, so "is it armed" is a
 * real question with a real answer, and one a recruiter should not have to read
 * server logs to get.
 */
export const getMeetBotQueue = async (_req: AuthRequest, res: Response) => {
  res.json({
    enabled: env.MEET_BOT_ENABLED,
    running: MeetBotManager.activeCount(),
    capacity: env.MEET_BOT_MAX_CONCURRENT,
    joinLeadMinutes: env.MEET_BOT_JOIN_LEAD_MINUTES,
    candidateWaitMinutes: env.MEET_BOT_CANDIDATE_WAIT_MINUTES,
    candidateGraceMinutes: env.MEET_BOT_CANDIDATE_GRACE_MINUTES,
    upcoming: await MeetBotManager.upcoming(10),
    serverTime: new Date().toISOString(),
  });
};

export const listMeetInterviews = async (req: AuthRequest, res: Response) => {
  const { status, search, limit = '50' } = req.query as Record<string, string>;
  const take = Math.min(200, Math.max(1, parseInt(limit, 10) || 50));

  const interviews = await prisma.sessionCandidate.findMany({
    where: {
      interviewSession: { userId: req.user!.userId },
      // Only interviews the bot drives; the built-in room has its own screens.
      meetBotRun: status ? { status: status as never } : { isNot: null },
      ...(search
        ? {
            OR: [
              { candidate: { name: { contains: search, mode: 'insensitive' as const } } },
              { candidate: { email: { contains: search, mode: 'insensitive' as const } } },
              { interviewSession: { title: { contains: search, mode: 'insensitive' as const } } },
            ],
          }
        : {}),
    },
    include: {
      candidate: true,
      interviewSession: true,
      meetBotRun: true,
      report: { select: { id: true } },
      transcript: { select: { id: true, _count: { select: { turns: true } } } },
    },
    orderBy: { interviewSession: { scheduledAt: 'desc' } },
    take,
  });

  res.json({ interviews: interviews.map(present) });
};

export const getMeetInterview = async (req: AuthRequest, res: Response) => {
  const interview = await ownedInterview(req, param(req, 'id'));
  const body = present(interview);

  res.json({
    ...body,
    codingUrlReachable: body.codingUrl ? await codingPageReachable() : null,
  });
};

/** Deliberately small: polled as a fallback whenever the socket is down. */
export const getMeetInterviewStatus = async (req: AuthRequest, res: Response) => {
  const interview = await ownedInterview(req, param(req, 'id'));
  const run = interview.meetBotRun;

  res.json({
    interviewId: interview.id,
    status: MeetBotManager.statusOf(interview.id) ?? run?.status ?? 'SCHEDULED',
    detail: run?.statusDetail ?? null,
    errorCode: run?.errorCode ?? null,
    errorMessage: run?.errorMessage ?? null,
    live: MeetBotManager.isRunning(interview.id),
    joinedAt: run?.joinedAt ?? null,
    startedAt: run?.startedAt ?? null,
    endedAt: run?.endedAt ?? null,
    // Drives the running clock in the dashboard without a second request.
    elapsedSeconds: run?.joinedAt
      ? Math.max(0, Math.floor(((run.endedAt ?? new Date()).getTime() - run.joinedAt.getTime()) / 1000))
      : 0,
  });
};

export const getMeetInterviewTranscript = async (req: AuthRequest, res: Response) => {
  const interview = await ownedInterview(req, param(req, 'id'));

  const transcript = await prisma.interviewTranscript.findUnique({
    where: { sessionCandidateId: interview.id },
    include: { turns: { orderBy: { timestamp: 'asc' } } },
  });

  let questionNumber = 0;

  res.json({
    interviewId: interview.id,
    candidateName: interview.candidate.name,
    summary: transcript?.summary ?? null,
    messages: (transcript?.turns ?? []).map((turn) => ({
      id: turn.id,
      speaker: turn.speaker,
      message: turn.text,
      timestamp: turn.timestamp,
      round: turn.round,
      // Numbered as they were asked, so a recruiter reading the transcript can
      // line it up with the question set.
      questionNumber: turn.speaker === 'AI' && turn.questionId ? ++questionNumber : null,
    })),
  });
};

