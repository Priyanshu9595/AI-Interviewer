/**
 * The recruiter-facing API for interviews the AI runs inside a meeting the
 * recruiter already created.
 *
 * The form is deliberately one screen — candidate, role, link, time — but each
 * submission produces the same objects the rest of the platform works with: a
 * session, a candidate, a question set and a transcript. Reports, analytics and
 * exports therefore work on these interviews with no special-casing anywhere.
 */

const createSchema = z.object({
  candidateName: z.string().min(2, 'Enter the candidate’s name'),
  candidateEmail: z.string().email('Enter a valid candidate email'),
  jobTitle: z.string().min(2, 'Enter the job title'),
  jobDescription: z
    .string()
    .min(30, 'The job description needs at least 30 characters to generate good questions'),
  requiredSkills: z.array(z.string().min(1)).min(1, 'List at least one required skill'),
  durationMinutes: z.coerce.number().int().min(10).max(180).default(30),
  meetLink: z.string().min(1, 'Paste the meeting link'),
  scheduledAt: z.string().min(1),

  experienceLevel: z.string().default('Mid-level (3-5 years)'),
  type: z.enum(['TECHNICAL', 'HR', 'MIXED']).default('MIXED'),
  personality: z.enum(['FRIENDLY', 'NEUTRAL', 'FORMAL', 'CHALLENGING']).default('FRIENDLY'),
  language: z.string().default('en-US'),
  passMark: z.coerce.number().int().min(1).max(10).default(6),
  /** Skip the invitation email when the recruiter has already sent the link. */
  sendInvite: z.boolean().default(true),
  /**
   * Include a coding exercise. A meeting call has no shared editor, so the
   * candidate opens a browser tab for it — the link is emailed with the
   * invitation and posted in the meeting chat when the round starts.
   */
  codingEnabled: z.boolean().default(false),
});

/**
 * Whether the coding editor page actually exists at APP_URL.
 *
 * This is the one link in the system that is generated by the backend but
 * served by the frontend, so the two can disagree — a backend running locally
 * against a deployment that predates the coding page hands the candidate a 404
 * in the middle of their interview, with no way to recover.
 *
 * The token in the probe URL is deliberately meaningless: a missing *route*
 * 404s for every token, and a present route renders for any of them, so this
 * answers "is the page deployed" without touching a real interview.
 *
 * Cached because it is the same answer for every interview on a given
 * deployment, and this runs on the interview page.
 */
let reachabilityCache: { at: number; ok: boolean } | null = null;
const REACHABILITY_TTL_MS = 60_000;

async function codingPageReachable(): Promise<boolean> {
  if (reachabilityCache && Date.now() - reachabilityCache.at < REACHABILITY_TTL_MS) {
    return reachabilityCache.ok;
  }

  let ok = false;
  try {
    const res = await fetch(`${env.APP_URL}/interview/reachability-probe/code`, {
      method: 'GET',
      redirect: 'follow',
      signal: AbortSignal.timeout(6_000),
    });
    ok = res.status === 200;
    if (!ok) {
      console.warn(
        `[config] the coding editor page is not deployed at ${env.APP_URL} (HTTP ${res.status}). ` +
          'Candidates will get a 404. Point APP_URL at a frontend that has it, or deploy the current build.',
      );
    }
  } catch {
    // Unreachable is not the same as absent, but the candidate cannot tell.
    ok = false;
  }

  reachabilityCache = { at: Date.now(), ok };
  return ok;
}

/**
 * Resolves the interview and proves the caller owns it.
 *
 * Every endpoint below runs this first: the id is a bare uuid in the URL, and
 * without the ownership clause any signed-in recruiter could read any
 * candidate's transcript.
 */
async function ownedInterview(req: AuthRequest, id: string) {
  const interview = await prisma.sessionCandidate.findFirst({
    where: { id, interviewSession: { userId: req.user!.userId } },
    include: {
      candidate: true,
      interviewSession: true,
      meetBotRun: true,
      report: { select: { id: true } },
      transcript: { select: { id: true, _count: { select: { turns: true } } } },
    },
  });

  if (!interview) throw notFound('Interview not found');
  return interview;
}

/**
 * Why there is, or is not, a report yet.
 *
 * Without this the dashboard can only say "no report", which covers a candidate
 * who never showed up, an interview that finished thirty seconds ago, and a
 * provider quota that will clear in twenty minutes. Those need three different
 * reactions from the recruiter, so they are told apart here.
 */
function evaluationState(interview: Awaited<ReturnType<typeof ownedInterview>>) {
  const turns = interview.transcript?._count.turns ?? 0;

  const state = interview.report
    ? 'READY'
    : interview.status === 'INCOMPLETE'
      ? 'NOT_SCORED_INCOMPLETE'
      : interview.status !== 'COMPLETED'
        ? 'NOT_INTERVIEWED'
        : turns === 0
          ? 'NO_TRANSCRIPT'
          : interview.evaluationRetryAt
            ? 'RETRYING'
            : interview.evaluationAttempts > 0
              ? 'FAILED'
              : 'PENDING';

  const EXPLANATION: Record<string, string> = {
    READY: 'The report is ready.',
    PENDING: 'The interview is finished; the report is being written.',
    RETRYING: 'Report generation hit a temporary problem and will be retried automatically.',
    FAILED: 'Report generation failed. Use Retry to try again.',
    NO_TRANSCRIPT: 'Nothing was said during the interview, so there is nothing to score.',
    NOT_INTERVIEWED: 'The interview has not finished yet.',
    NOT_SCORED_INCOMPLETE:
      'The candidate left before the interviewer finished. Partial interviews are not scored, because a low score caused by walking out would misrepresent them. The transcript is kept in full.',
  };

  return {
    state,
    explanation: EXPLANATION[state] ?? '',
    reportId: interview.report?.id ?? null,
    attempts: interview.evaluationAttempts,
    error: interview.evaluationError,
    nextRetryAt: interview.evaluationRetryAt,
    transcriptTurns: turns,
  };
}

/** The shape the dashboard renders. */
function present(interview: Awaited<ReturnType<typeof ownedInterview>>) {
  const run = interview.meetBotRun;
  const session = interview.interviewSession;

  return {
    id: interview.id,
    candidateName: interview.candidate.name,
    candidateEmail: interview.candidate.email,
    jobTitle: session.title,
    jobDescription: session.jobDescription,
    requiredSkills: session.skills,
    durationMinutes: session.durationMinutes,
    scheduledAt: session.scheduledAt,
    meetLink: run?.meetLink ?? session.meetingLink,
    platform: run?.platform ?? 'GOOGLE_MEET',
    platformLabel: PLATFORM_LABEL[(run?.platform ?? 'GOOGLE_MEET') as keyof typeof PLATFORM_LABEL] ?? 'Meeting',
    /** Whether this platform needs the bot signed in, for the setup hint. */
    requiresSignIn: (() => {
      try {
        return driverFor((run?.platform ?? 'GOOGLE_MEET') as never).requiresSignIn;
      } catch {
        return false;
      }
    })(),

    status: run?.status ?? 'SCHEDULED',
    statusDetail: run?.statusDetail ?? null,
    errorCode: run?.errorCode ?? null,
    errorMessage: run?.errorMessage ?? null,

    joinAt: run?.joinAt ?? null,
    startedAt: run?.startedAt ?? null,
    joinedAt: run?.joinedAt ?? null,
    endedAt: run?.endedAt ?? null,
    attempts: run?.attempts ?? 0,

    candidateStatus: interview.status,
    live: MeetBotManager.isRunning(interview.id),
    hasReport: Boolean(interview.report),
    evaluation: evaluationState(interview),
    sessionId: session.id,

    codingEnabled: session.codingEnabled,
    /**
     * Where the candidate writes their code. Surfaced so the recruiter can send
     * it themselves — the bot posts it in the meeting chat, but chat panels are
     * the flakiest part of every one of these clients and a recruiter with the
     * link in front of them is never stuck.
     */
    codingUrl: session.codingEnabled ? `${env.APP_URL}/interview/${interview.accessToken}/code` : null,
  };
}

