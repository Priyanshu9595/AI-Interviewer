export const startMeetInterview = async (req: AuthRequest, res: Response) => {
  const interview = await ownedInterview(req, param(req, 'id'));
  if (!interview.meetBotRun) throw badRequest('This interview has no Google Meet link attached');

  try {
    await MeetBotManager.start(interview.id, { manual: true });
  } catch (err) {
    if (err instanceof BotError) {
      // Capacity and "already running" are states of the world, not bad
      // requests; 409 lets the dashboard say so plainly.
      throw conflict(err.detail ? `${err.message} (${err.detail})` : err.message);
    }
    throw err;
  }

  res.json(present(await ownedInterview(req, interview.id)));
};

/**
 * Forces a fresh attempt at the report.
 *
 * The scheduler already retries on its own with backoff, but a recruiter
 * watching a provider quota tick down should not have to wait for the next
 * tick once it clears.
 */
export const retryMeetInterviewReport = async (req: AuthRequest, res: Response) => {
  const interview = await ownedInterview(req, param(req, 'id'));

  if (interview.report) {
    res.json({ ...evaluationState(interview), alreadyExisted: true });
    return;
  }

  if (interview.status !== 'COMPLETED') {
    throw conflict(
      interview.status === 'INCOMPLETE'
        ? 'This interview was not finished, so it is deliberately not scored.'
        : 'This interview has not been completed, so there is nothing to score yet.',
    );
  }

  // Clear the backoff first, or the queue will decline to run this attempt.
  await prisma.sessionCandidate.update({
    where: { id: interview.id },
    data: { evaluationRetryAt: null, evaluationAttempts: 0, evaluationError: null },
  });

  const ok = await EvaluationQueue.run(interview.id);
  res.json({ ...evaluationState(await ownedInterview(req, interview.id)), ranNow: ok });
};

export const stopMeetInterview = async (req: AuthRequest, res: Response) => {
  const interview = await ownedInterview(req, param(req, 'id'));
  const reason = String((req.body as { reason?: string })?.reason ?? 'Stopped from the dashboard').slice(0, 200);

  const stopped = await MeetBotManager.stop(interview.id, reason);
  if (!stopped) throw conflict('This interview is not running');

  res.json(present(await ownedInterview(req, interview.id)));
};
