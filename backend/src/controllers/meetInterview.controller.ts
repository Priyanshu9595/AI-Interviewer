export const createMeetInterview = async (req: AuthRequest, res: Response) => {
  const data = createSchema.parse(req.body);

  // Fail on the link before anything is written. A recruiter who mistyped it
  // should find out while the form is open, not at the scheduled time.
  let link;
  try {
    link = parseMeetingLink(data.meetLink);
  } catch (err) {
    throw badRequest(
      err instanceof BotError ? err.message : 'That is not a meeting link the AI interviewer can join',
    );
  }

  const scheduledAt = new Date(data.scheduledAt);
  if (Number.isNaN(scheduledAt.getTime())) throw badRequest('scheduledAt is not a valid date');

  const email = data.candidateEmail.trim().toLowerCase();

  // Candidates are shared across sessions, so the same person interviewed twice
  // keeps one record and one history.
  const candidate = await prisma.candidate.upsert({
    where: { email },
    create: { email, name: data.candidateName.trim() },
    update: { name: data.candidateName.trim() },
  });

  const session = await prisma.interviewSession.create({
    data: {
      userId: req.user!.userId,
      title: data.jobTitle.trim(),
      jobDescription: data.jobDescription,
      skills: data.requiredSkills.map((s) => s.trim()).filter(Boolean),
      experienceLevel: data.experienceLevel,
      type: data.type,
      scheduledAt,
      durationMinutes: data.durationMinutes,
      status: 'SCHEDULED',
      meetingProvider: link.platform,
      // The candidate is emailed the link they were given, not the web-client
      // URL the bot uses to get around Zoom's app launcher.
      meetingLink: link.displayUrl,
      personality: data.personality,
      language: data.language,
      passMark: data.passMark,
      // The coding round moves to a browser tab the candidate opens; recording
      // and video analysis have no client to capture from at all, so they stay
      // off rather than being silently ignored.
      codingEnabled: data.codingEnabled,
      recordingEnabled: false,
      videoAnalysisEnabled: false,
    },
  });

  const interview = await prisma.sessionCandidate.create({
    data: { interviewSessionId: session.id, candidateId: candidate.id },
  });

  await prisma.meetBotRun.create({
    data: {
      sessionCandidateId: interview.id,
      meetLink: link.displayUrl,
      platform: link.platform,
      status: 'SCHEDULED',
      // Early enough to be admitted, settled and waiting when the candidate
      // arrives, rather than knocking on the lobby door at the start time.
      joinAt: new Date(scheduledAt.getTime() - env.MEET_BOT_JOIN_LEAD_MINUTES * 60_000),
    },
  });

  // Several seconds of LLM work; the recruiter should not wait for it. The
  // state machine loads questions when the interview starts, by which point
  // this has long finished.
  void QuestionGenerationService.generateAndSave(session.id).catch((err) =>
    console.error(`[meet-interview] question generation failed for ${session.id}:`, err.message),
  );

  if (data.sendInvite) {
    await SchedulerService.scheduleFor(interview.id).catch((err) =>
      console.error(`[meet-interview] could not queue reminders for ${interview.id}:`, err.message),
    );
  }

  // Scheduled for now, or for less than the lead time away: start at once
  // rather than leaving the recruiter watching nothing until the next tick.
  void MeetBotManager.startIfDue(interview.id);

  const created = await ownedInterview(req, interview.id);

  res.status(201).json({
    ...present(created),
    // Checked here, while the recruiter is still looking at the form, because
    // finding out mid-interview that the editor 404s cannot be recovered from.
    codingUrlReachable: data.codingEnabled ? await codingPageReachable() : null,
  });
};

